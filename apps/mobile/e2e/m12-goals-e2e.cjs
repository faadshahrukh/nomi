const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  const page = await b.newPage({ viewport: { width: 400, height: 1100 } });
  const errs = []; page.on('pageerror', (e) => errs.push(e.message));
  let fails = 0; const ok = (n, c) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + n); };
  const vis = async (t) => { for (const l of await page.getByText(t, { exact: false }).all()) if (await l.isVisible().catch(() => false)) return true; return false; };
  const wait = (ms = 400) => page.waitForTimeout(ms);
  const btn = (n, o = {}) => page.getByRole('button', { name: n, ...o });
  await page.goto('http://localhost:8099/', { waitUntil: 'networkidle' }); await wait(900);
  const perDay = async () => (await page.getByText(/per day, about/).first().innerText().catch(() => ''));
  await page.getByRole('tab', { name: 'Planning' }).click(); await wait(300);
  await btn('Goals', { exact: true }).click(); await wait(300);
  await btn('Add a goal').click(); await wait(300);
  await btn('Add goal').click(); await wait(300);
  ok('empty goal rejected in plain words', await vis('Give the goal a name') && await vis('amount you want to reach'));
  await page.getByLabel('Name', { exact: true }).fill('Laptop');
  await page.getByLabel(/Target amount/).fill('90000');
  await page.getByLabel('Reach it by (optional)').fill('2024-01-01');
  await btn('Add goal').click(); await wait(300);
  ok('a date in the past is rejected', await vis('date in the future'));
  await page.getByLabel('Reach it by (optional)').fill('');
  await page.getByLabel('Put aside each month (optional)').fill('8000');
  await btn('Add goal').click(); await wait(700);
  ok('goal appears with progress', await btn('Laptop goal. Tap to edit.').isVisible() && await vis('Laptop'));
  await btn('Laptop goal. Tap to edit.').click(); await wait(300);
  ok('editing shows the saved target', (await page.getByLabel(/Target amount/).inputValue()) === '90000');
  await page.getByLabel(/Target amount/).fill('100000'); await btn('Save changes').click(); await wait(600);
  ok('edit saved', await vis('of ৳1,00,000'));
  await page.getByRole('tab', { name: 'Home' }).click(); await wait(500);
  await page.getByRole('button', { name: /Safe to Spend\./ }).click(); await wait(300);
  await btn('Details and safety buffer').click(); await wait(500);
  ok('the new goal is counted in Safe to Spend', await vis('Goals counted') && await vis('Laptop'));
  ok('no page errors', errs.length === 0); if (errs.length) console.log(errs);
  await b.close(); process.exit(fails ? 1 : 0);
})();
