const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  const ctx = await b.newContext({ viewport: { width: 400, height: 1100 }, acceptDownloads: true });
  const page = await ctx.newPage();
  const errs = []; page.on('pageerror', (e) => errs.push(e.message));
  let fails = 0; const ok = (n, c) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + n); };
  const vis = async (t) => { for (const l of await page.getByText(t, { exact: false }).all()) if (await l.isVisible().catch(() => false)) return true; return false; };
  const wait = (ms = 400) => page.waitForTimeout(ms);
  const btn = (n, o = {}) => page.getByRole('button', { name: n, ...o });
  await page.goto('http://localhost:8099/', { waitUntil: 'networkidle' }); await wait(900);
  await page.getByRole('tab', { name: 'Profile' }).click(); await wait(400);
  ok('profile shows backup row as off', await btn(/Backup and sync/).isVisible());
  await btn(/Privacy and data/).click(); await wait(500);
  ok('privacy screen explains where data lives', await vis('Where your data lives') && await vis('Audio is never stored'));
  const [dl] = await Promise.all([page.waitForEvent('download'), btn('Everything (JSON)').click()]);
  const path = await dl.path(); const json = JSON.parse(require('fs').readFileSync(path, 'utf8'));
  ok('JSON export is the full, versioned document', dl.suggestedFilename() === 'nomi-export-2025-03-15.json' && json.format === 'nomi-export' && json.version === 1 && json.transactions.length > 50 && json.accounts.length >= 3 && Array.isArray(json.audit));
  ok('exact minor units, not rounded', json.transactions.every((t) => Number.isInteger(t.amountMinor)));
  const [dl2] = await Promise.all([page.waitForEvent('download'), btn('Transactions (CSV)').click()]);
  const csv = require('fs').readFileSync(await dl2.path(), 'utf8');
  ok('CSV has a header and one row per live transaction', csv.startsWith('Date,Type,Amount,Currency,Category,Merchant,Account') && csv.trim().split('\r\n').length === json.transactions.filter((t) => !t.deletedAt).length + 1);
  ok('export confirms with a toast', await vis('Your export is ready'));
  ok('demo data is not offered for deletion', await vis('example data, which is not yours') && !(await btn('Delete data on this device').isVisible().catch(() => false)));
  await btn('Off (recommended)').click().catch(() => {});
  await page.getByRole('radio', { name: /On/ }).first().click().catch(() => {}); await wait(400);
  ok('retention explains itself', await vis('thrown away once understood') || await vis('original sentence is kept'));
  await btn('Back').click(); await wait(400);
  await btn(/Notifications/).click(); await wait(500);
  ok('notifications screen says what it sends and that amounts are never included', await vis('never include amounts') && await vis('What would be sent'));
  ok('example data does not schedule real reminders', await vis('Reminders are off for the example data'));
  await btn('Back').click(); await wait(400);
  await btn(/Backup and sync/).click(); await wait(500);
  ok('sync screen says why it is off and what is and is not synced', await vis('example data') && await vis('What is backed up') && await vis('Not synced'));
  ok('no page errors', errs.length === 0); if (errs.length) console.log(errs);
  await b.close(); process.exit(fails ? 1 : 0);
})();
